<#
.SYNOPSIS
    Generates src\kxgdi.def: forwards every named gdi32 export to the real
    gdi32.dll, except the functions kxgdi implements itself.

.DESCRIPTION
    Takes the export names from one or more gdi32.dll files (default: the one
    of this PC) and builds the union. Forwarders to names that do not exist in
    the Windows 7 gdi32.dll are harmless: they only fail if a program actually
    imports such a name, which is exactly what happens without kxgdi.

    If you get a gdi32.dll from a Windows 7 machine, pass it as well so that
    exports which only exist on Windows 7 are covered too:

        .\gen-def.ps1 -Gdi32 C:\Windows\System32\gdi32.dll, D:\win7\gdi32.dll

.NOTES
    Requires dumpbin.exe (Visual Studio C++ build tools).
#>
param(
    [string[]] $Gdi32 = @("$env:SystemRoot\System32\gdi32.dll"),
    [string]   $Dumpbin = ""
)

$ErrorActionPreference = 'Stop'

# Functions implemented in kxgdi.c: export name => internal symbol
$Implemented = [ordered]@{
    'D3DKMTOpenAdapterFromLuid' = 'Ext_D3DKMTOpenAdapterFromLuid'
}

if (-not $Dumpbin) {
    $vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
    $vs = & $vswhere -latest -products * -property installationPath
    $Dumpbin = Get-ChildItem "$vs\VC\Tools\MSVC\*\bin\Hostx64\x64\dumpbin.exe" |
        Sort-Object FullName -Descending | Select-Object -First 1 -ExpandProperty FullName
}
if (-not $Dumpbin -or -not (Test-Path $Dumpbin)) { throw "dumpbin.exe not found (pass -Dumpbin)" }

$names = New-Object 'System.Collections.Generic.SortedSet[string]' ([StringComparer]::Ordinal)

foreach ($dll in $Gdi32) {
    if (-not (Test-Path $dll)) { throw "$dll not found" }
    $out = & $Dumpbin /nologo /exports $dll
    if ($LASTEXITCODE -ne 0) { throw "dumpbin failed for $dll (exit code $LASTEXITCODE)" }

    $count = 0
    $noName = 0
    foreach ($line in $out) {
        # "  ordinal hint RVA      name"  or forwarded: "  ordinal hint          name (forwarded to ...)"
        if ($line -match '^\s+\d+\s+[0-9A-F]+\s+(?:[0-9A-F]{8}\s+)?([A-Za-z_][A-Za-z0-9_@?$]*)(\s+\(forwarded to .*\))?\s*$') {
            [void] $names.Add($Matches[1])
            $count++
        } elseif ($line -match '\[NONAME\]') {
            $noName++
        }
    }

    # Every gdi32.dll since Windows 7 has several hundred named exports; far
    # fewer means a wrong file or unexpected dumpbin output, and the .def files
    # would be incomplete. Nothing has been written at this point.
    if ($count -lt 500) { throw "$dll : only $count named exports found - not a gdi32.dll, or unexpected dumpbin output" }
    Write-Host "$dll : $count named exports"

    # Exports without a name can only be imported by ordinal. They are internal
    # to Windows (Windows 11 has a few in gdi32), and their ordinals differ
    # between Windows versions, so forwarding them could even reach the wrong
    # function on Windows 7. They are skipped on purpose.
    if ($noName -gt 0) {
        Write-Warning "$dll : $noName exports without a name (ordinal only) are not forwarded"
    }
}

$root = Split-Path $PSScriptRoot -Parent
$defPath = Join-Path $root 'src\kxgdi.def'

$sb = New-Object System.Text.StringBuilder
[void] $sb.AppendLine(';; Generated by tools\gen-def.ps1 - do not edit by hand.')
[void] $sb.AppendLine(";; Sources: $($Gdi32 -join ', ')")
[void] $sb.AppendLine('LIBRARY kxgdi')
[void] $sb.AppendLine('EXPORTS')
[void] $sb.AppendLine('    ;; implemented in kxgdi.c')
foreach ($k in $Implemented.Keys) {
    [void] $sb.AppendLine("    $k=$($Implemented[$k])")
}
[void] $sb.AppendLine('')
[void] $sb.AppendLine('    ;; forwarded to the real gdi32.dll')
$fwd = 0
foreach ($n in $names) {
    if ($Implemented.Contains($n)) { continue }
    # No spaces around '=': link.exe only recognizes forwarders written as name=dll.name
    [void] $sb.AppendLine("    $n=gdi32.$n")
    $fwd++
}

$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText($defPath, $sb.ToString(), $utf8)
Write-Host "Wrote $defPath ($($Implemented.Count) implemented, $fwd forwarded)"

# Import library definition for gdi32. link.exe checks every "name=gdi32.name"
# forwarder against the gdi32 import library in the link, so it must contain
# all forwarded names (plus the functions kxgdi.c calls itself).
$libDef = Join-Path $root 'imports\gdi32.def'
$sb = New-Object System.Text.StringBuilder
[void] $sb.AppendLine(';; Generated by tools\gen-def.ps1 - import definitions for gdi32.lib (no Windows SDK needed).')
[void] $sb.AppendLine('LIBRARY gdi32.dll')
[void] $sb.AppendLine('EXPORTS')
foreach ($n in $names) {
    [void] $sb.AppendLine("    $n")
}
[System.IO.File]::WriteAllText($libDef, $sb.ToString(), $utf8)
Write-Host "Wrote $libDef ($($names.Count) names)"
